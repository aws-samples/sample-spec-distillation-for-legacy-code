#!/usr/bin/env python3
"""Simple one-prompt-per-file baseline for spec extraction.

For each source file: one Bedrock Converse call with the file (line-numbered) and a single
instruction to extract business rules, workflows, states and exceptions with line citations.
Outputs are concatenated into <out>/spec.md; per-call tokens go to <out>/tokens.jsonl and the
per-machine log bedrock_util.DEFAULT_LOG (eval/logs/local/bedrock_calls.jsonl, gitignored).

Usage: python3 eval/baseline.py --source-root synthetic-corpus/ap-invoices \
           --out eval/runs/baseline-ap [--glob '*.vb']
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bedrock_util import MODEL_ID, converse, summarize_log  # noqa: E402

PROMPT = """Extract the business rules, workflows, states and exceptions implemented in the
following source file. Cite the supporting lines for every item using the format
`{name}:L<start>-L<end>` (or `{name}:L<n>` for a single line).

File: {name}
```
{body}
```
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source-root", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--glob", default="*")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    log = a.out / "tokens.jsonl"
    if log.exists():
        log.unlink()
    files = sorted(p for p in a.source_root.rglob(a.glob) if p.is_file() and p.name != "ANSWER_KEY.yaml")
    sections = [f"# Baseline spec: {a.source_root.name}\n",
                f"_Generated by eval/baseline.py: one `{MODEL_ID}` call per file, no cross-file context._\n"]
    for p in files:
        rel = str(p.relative_to(a.source_root))
        lines = p.read_text(errors="replace").splitlines()
        body = "\n".join(f"{i:4d} | {l}" for i, l in enumerate(lines, 1))
        t0 = time.time()
        r = converse(PROMPT.format(name=rel, body=body), max_tokens=8000, tag=f"baseline:{rel}")
        # duplicate the record into the run-local log
        with open(log, "a") as f:
            f.write(json.dumps({"tag": f"baseline:{rel}", "input_tokens": r["input_tokens"],
                                "output_tokens": r["output_tokens"], "cost_usd": r["cost_usd"]}) + "\n")
        print(f"{rel}: in={r['input_tokens']} out={r['output_tokens']} ${r['cost_usd']:.4f} "
              f"({time.time() - t0:.1f}s, stop={r['stop_reason']})")
        sections.append(f"\n---\n\n# File: {rel}\n\n{r['text'].strip()}\n")
    (a.out / "spec.md").write_text("\n".join(sections))
    tot = summarize_log(log)
    (a.out / "generation_usage.json").write_text(json.dumps(tot, indent=2))
    print("total:", tot)


if __name__ == "__main__":
    main()
