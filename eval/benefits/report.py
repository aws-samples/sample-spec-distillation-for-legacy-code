"""Merge benefit-eval results from several tools into one markdown comparison (one table per benefit).

Usage:
  python3 eval/benefits/report.py --results RUN_A/ RUN_B/qa.json ... [--out comparison.md] [--json out.json]
  python3 eval/benefits/report.py --glob 'eval/benefits/runs/*/*.json' --out comparison.md

Each input is a result JSON written by insights.py / qa_eval.py / impact_eval.py / fieldapp_eval.py
(identified by its "benefit" field), or a directory searched for insights.json, qa.json, impact.json and
fieldapp.json. Rows are tools, columns are summary metrics; the headline metrics for each benefit come first.
"""
from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path

RESULT_FILES = ("insights.json", "qa.json", "impact.json", "fieldapp.json")
ORDER = ["B1 modernization insight", "B2/B5 Q&A", "B3 impact analysis", "B4 field-app spec"]
HEADLINE = {
    "B1 modernization insight": ["issue_described_any_pct", "issue_flagged_same_pct", "issue_flagged_any_pct",
                                 "flag_precision_keyed_pct", "flag_precision_true_pct", "overall_recall_full_pct",
                                 "incorrect_findings"],
    "B2/B5 Q&A": ["correct_pct", "score_pct", "wrong", "engineer_correct_pct", "product_correct_pct",
                  "trick_abstain_pct", "plain_language_avg", "citation_supported_pct", "citation_validity_pct"],
    "B3 impact analysis": ["location_recall_pct", "location_precision_pct", "file_recall_pct", "file_precision_pct",
                           "rule_recall_pct", "all_copies_found_pct", "contract_recall_pct", "report_recall_pct"],
    "B4 field-app spec": ["recall_full_pct", "recall_any_pct", "wrong_requirements", "invented_requirements",
                          "precision_correct_pct", "key_items_contradicted"],
}
COST = ["answer_tokens_in", "answer_tokens_out", "answer_cost_usd", "latency_avg_s", "latency_s"]


def collect(paths: list[str]) -> list[dict]:
    out = []
    for p in paths:
        p = Path(p)
        files = [p / f for f in RESULT_FILES if (p / f).exists()] if p.is_dir() else [p]
        for f in files:
            try:
                d = json.loads(f.read_text())
            except Exception:
                continue
            if isinstance(d, dict) and "benefit" in d and "summary" in d:
                d["_path"] = str(f)
                out.append(d)
    return out


def fmt(v):
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:g}"
    return str(v)


def build(results: list[dict], all_metrics: bool) -> tuple[str, dict]:
    by = {}
    for r in results:
        by.setdefault(r["benefit"], []).append(r)
    L = ["# Benefit evaluation: tool comparison", "",
         "Generated by `eval/benefits/report.py`. Each row is one tool run; spend includes judge calls.", ""]
    merged = {}
    for b in sorted(by, key=lambda x: ORDER.index(x) if x in ORDER else 99):
        rs = by[b]
        keys = [k for k in HEADLINE.get(b, []) if any(k in r["summary"] for r in rs)]
        keys += [k for k in COST if any(k in r["summary"] for r in rs) and k not in keys]
        if all_metrics:
            for r in rs:
                keys += [k for k in r["summary"] if k not in keys]
        L += [f"## {b}", "", "| Tool | " + " | ".join(keys) + " | run spend $ |", "|---|" + "---|" * (len(keys) + 1)]
        for r in rs:
            spend = (r.get("budget") or {}).get("cost_usd")
            stop = " (stopped)" if (r.get("budget") or {}).get("stopped") else ""
            L.append(f"| {r['tool']}{stop} | " + " | ".join(fmt(r["summary"].get(k)) for k in keys)
                     + f" | {fmt(spend)} |")
        L += ["", "Sources: " + ", ".join(f"`{r['_path']}`" for r in rs), ""]
        merged[b] = [{"tool": r["tool"], "path": r["_path"], "summary": r["summary"], "budget": r.get("budget")}
                     for r in rs]
    return "\n".join(L) + "\n", merged


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", nargs="*", default=[], help="result JSON files or run directories")
    ap.add_argument("--glob", action="append", default=[], help="glob for result files/dirs; repeatable")
    ap.add_argument("--all-metrics", action="store_true", help="include every summary metric, not just headline + cost")
    ap.add_argument("--out", type=Path, help="markdown output (default: stdout)")
    ap.add_argument("--json", type=Path, help="optional merged JSON output")
    a = ap.parse_args()
    paths = list(a.results) + [p for g in a.glob for p in sorted(glob.glob(g))]
    results = collect(paths)
    if not results:
        raise SystemExit("no result files found")
    md, merged = build(results, a.all_metrics)
    if a.out:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_text(md)
        print(f"wrote {a.out} ({len(results)} results)")
    else:
        print(md)
    if a.json:
        a.json.write_text(json.dumps(merged, indent=2))


if __name__ == "__main__":
    main()
