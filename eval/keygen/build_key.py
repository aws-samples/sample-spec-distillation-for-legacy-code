"""Build a draft answer key for a code base that has none.

    python3 eval/keygen/build_key.py --source /tmp/eshop --commit 4da8212 \
        --repo-url https://github.com/dotnet-architecture/eShopOnWeb \
        --out eval/keys/eshoponweb/ANSWER_KEY.draft.yaml [--facts facts.json] \
        [--tests-glob 'tests/**'] [--docs 'README.md'] [--llm-draft --max-usd 2] \
        [--plant 8 --seed 42 --plant-out /tmp/eshop-mutated]

Pipeline (see eval/keygen/README.md):

1. HARVEST (deterministic, no AI)   kg_harvest.py   guards, throws, exceptions, enums, constants,
   thresholds, DataAnnotations, FluentValidation, EF Core config, authorization, routes, MediatR,
   specifications, entity invariants, SQL constraints/triggers/procs
2. MINE TESTS (independent evidence) kg_testmine.py  one "protected behaviour" per test method
3. DOCS (optional, --docs)           kg_docs.py      markdown feature bullets, evidence Inferred
4. MERGE / DEDUPE                    kg_merge.py     provenance kept, `corroborated` flag
5. AI DRAFT (optional, --llm-draft)  kg_llm.py       bounded, cost-capped, citations verified
6. PLANTED PROBLEMS (--plant N)      eval/mutate     C#-aware mutations, items merged into the key

Every item is ``status: unreviewed`` until ``review.py --apply`` records a human decision.
The key builder never reads pipeline outputs: it keeps the key independent of what it scores.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import kg_docs                                               # noqa: E402
import kg_harvest                                            # noqa: E402
import kg_merge                                              # noqa: E402
import kg_source                                             # noqa: E402
import kg_testmine                                           # noqa: E402
from kg_source import BUILDER_NAME, BUILDER_VERSION          # noqa: E402

try:
    import yaml
except Exception:                                            # pragma: no cover
    yaml = None

INDEPENDENCE_RULE = (
    "Built only from the source tree at the pinned commit (code, tests, docs). No output of the "
    "pipeline under test was read, so the key cannot share the pipeline's mistakes."
)


def counts(items: list[dict]) -> dict:
    by_source = Counter(s for it in items for s in it.get("source", []))
    by_source_kind = Counter(k for it in items for k in sorted({x.split(":")[0] for x in it.get("source", [])}))
    return {
        "total": len(items),
        "by_type": dict(sorted(Counter(it["type"] for it in items).items())),
        "by_status": dict(sorted(Counter(it.get("status", "unreviewed") for it in items).items())),
        "by_source": dict(sorted(by_source_kind.items())),
        "by_detector": dict(sorted(by_source.items())),
        "by_evidence_class": dict(sorted(Counter(it.get("evidence_class") for it in items).items())),
        "corroborated": sum(1 for it in items if "corroborated" in it.get("flags", [])),
    }


def dump(obj) -> str:
    return yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=100, allow_unicode=True)


def header(meta: dict) -> str:
    lines = [
        "# Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.",
        "# SPDX-License-Identifier: MIT-0",
        "#",
        f"# DRAFT ANSWER KEY generated by {BUILDER_NAME} {BUILDER_VERSION} (eval/keygen/build_key.py).",
        f"# Source: {meta.get('repo_url') or meta.get('source_root')} @ {meta.get('commit') or '?'}",
    ]
    if meta.get("source_license"):
        lines.append(f"# Short code snippets quoted in `snippet:` / `provenance:` are from that repository "
                     f"({meta['source_license']} license);")
        lines.append("# the source itself is NOT committed here. Fetch it at the pinned commit to score.")
    lines += [
        "# Paths are relative to the repository root. Line ranges are 1-based and inclusive.",
        "# status: unreviewed | accepted | edited | rejected | planted. Score reviewed items only:",
        "#   python3 eval/keygen/review.py --key <reviewed.yaml> --filter-out <scored.yaml>",
        f"# Independence: {INDEPENDENCE_RULE}",
        "",
    ]
    return "\n".join(lines) + "\n"


def write_key(path: Path, meta: dict, items: list[dict]) -> None:
    meta = dict(meta)
    meta["counts"] = counts(items)
    doc = {"corpus": meta.pop("corpus"), "version": 1, "metadata": meta, "items": items}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header(meta) + dump(doc))


def git_commit_of(root: Path) -> str | None:
    try:
        r = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True,
                           text=True, timeout=10)
        return r.stdout.strip() or None
    except Exception:
        return None


def planted_items(mut_yaml: Path) -> list[dict]:
    d = yaml.safe_load(mut_yaml.read_text()) or {}
    out = []
    for it in d.get("items") or []:
        it = dict(it)
        cat = (it.get("mutation") or {}).get("category", "mutation")
        it["status"] = "planted"
        it["source"] = [f"planted:{cat}"]
        out.append(it)
    return out


def build(a) -> dict:
    src = Path(a.source)          # not resolved: the path is recorded in mutations.yaml as given
    if not src.is_dir():
        raise SystemExit(f"--source not found: {src}")
    facts = kg_source.load_facts(a.facts) if a.facts else None
    harvest_root = src
    mutation_report = None
    if a.plant:
        sys.path.insert(0, str(HERE.parent / "mutate"))
        import mutate                                         # noqa: E402
        pout = Path(a.plant_out or f"/tmp/{src.name}-mutated")
        mutation_report = mutate.run(src, pout, a.plant, a.seed, a.plant_categories.split(",") if a.plant_categories else None,
                                     exclude=mutate.DEFAULT_EXCLUDE,   # same as the mutate CLI and suites
                                     lang=a.plant_lang, roslyn_cmd=a.roslyn_cmd)
        harvest_root = pout / "corpus"
        if facts is not None:
            print("note: --facts describes the unmutated tree; using the regex index for the mutated tree",
                  file=sys.stderr)
            facts = None
        if a.mutations_out:
            Path(a.mutations_out).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(pout / "mutations.yaml", a.mutations_out)
    files = kg_source.load_tree(harvest_root, tests_glob=a.tests_glob or None)
    index = kg_source.Index(files, facts)
    cands = kg_harvest.harvest(files, index, facts)
    cands += kg_testmine.mine_tests(files, index, facts)
    if a.docs:
        cands += kg_docs.mine_docs(harvest_root, a.docs)
    clusters = kg_merge.merge(cands)
    items = kg_merge.to_items(clusters)
    llm_report = None
    if a.llm_draft:
        import kg_llm                                         # noqa: E402
        drafted, llm_report = kg_llm.draft(files, items, a.max_usd, model=a.llm_model,
                                           max_calls=a.llm_max_calls,
                                           log_path=Path(a.out).with_suffix(".llm_calls.jsonl"))
        clusters = kg_merge.merge(cands + drafted)
        items = kg_merge.to_items(clusters)
    if a.plant:
        items += planted_items(Path(a.plant_out or f"/tmp/{src.name}-mutated") / "mutations.yaml")
    meta = {
        "corpus": a.corpus or src.name,
        "repo_url": a.repo_url,
        "commit": a.commit or git_commit_of(src),
        "source_license": a.source_license,
        "builder": {"name": BUILDER_NAME, "version": BUILDER_VERSION},
        "generated": a.date or date.today().isoformat(),
        "reviewer": None,
        "reviewed": None,
        "independence": INDEPENDENCE_RULE,
        "inputs": {
            "structure_index": "facts (Roslyn/ScriptDom)" if index.from_facts else "regex scanner",
            "facts_sha256": hashlib.sha256(Path(a.facts).read_bytes()).hexdigest() if a.facts else None,
            "tests_glob": a.tests_glob or "auto (tests/ dirs and [Fact]/[Test]/[TestMethod] files)",
            "docs": a.docs or [],
            "files_scanned": len(files),
            "test_files": sum(1 for f in files.values() if f.is_test),
            "candidates": dict(sorted(Counter(c.source for c in cands).items())),
            "llm_draft": llm_report,
            "planted": ({"n": a.plant, "seed": a.seed, "applied": mutation_report["applied"],
                         "mutated_tree": str(harvest_root), "lang": mutation_report.get("lang"),
                         "roslyn_check": mutation_report.get("roslyn_check", {}).get("status"),
                         "mutations_yaml_sha256": mutation_report["mutations_yaml_sha256"]}
                        if mutation_report else None),
        },
    }
    write_key(Path(a.out), meta, items)
    return {"out": a.out, "counts": counts(items), "llm_draft": llm_report,
            "planted": meta["inputs"]["planted"]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", required=True, help="repository root (read-only)")
    ap.add_argument("--commit", help="commit SHA the key is pinned to (default: git rev-parse HEAD)")
    ap.add_argument("--repo-url", help="public URL of the repository, recorded in the key header")
    ap.add_argument("--source-license", help="license of the source repository (e.g. MIT), recorded "
                                             "next to the snippet attribution")
    ap.add_argument("--corpus", help="corpus name in the key (default: source dir name)")
    ap.add_argument("--out", required=True, help="key YAML to write")
    ap.add_argument("--facts", help="raw facts.json from runtimes/facts (Roslyn/ScriptDom); "
                                    "default: the regex structure scanner")
    ap.add_argument("--tests-glob", action="append", default=[],
                    help="fnmatch glob of test files (repeatable; default: tests/ dirs and files "
                         "with [Fact]/[Theory]/[Test]/[TestMethod])")
    ap.add_argument("--docs", action="append", default=[],
                    help="fnmatch glob of markdown docs to mine (repeatable; off by default)")
    ap.add_argument("--date", help="date recorded in the key (default: today); fix it for "
                                   "byte-identical output")
    g = ap.add_argument_group("AI draft (off by default)")
    g.add_argument("--llm-draft", action="store_true", help="one bounded pass proposing rules the "
                                                           "harvest missed; citations verified")
    g.add_argument("--max-usd", type=float, default=0.0, help="hard cap for --llm-draft (default 0: "
                                                              "no call can start)")
    g.add_argument("--llm-model", help="model id (default: the eval judge model, bedrock_util.MODEL_ID)")
    g.add_argument("--llm-max-calls", type=int, default=12)
    g = ap.add_argument_group("planted problems")
    g.add_argument("--plant", type=int, default=0, metavar="N", help="inject N mutations (eval/mutate)")
    g.add_argument("--seed", type=int, default=42)
    g.add_argument("--plant-out", help="mutation output dir (corpus/ + mutations.yaml); default "
                                       "/tmp/<source>-mutated")
    g.add_argument("--plant-lang", choices=["auto", "vb", "cs"], default="auto")
    g.add_argument("--plant-categories", help="comma-separated mutation categories")
    g.add_argument("--mutations-out", help="also copy mutations.yaml here")
    g.add_argument("--roslyn-cmd", help="facts-tool command for the C# Roslyn parse check "
                                        "(see eval/mutate/mutate.py --roslyn-cmd)")
    a = ap.parse_args(argv)
    if a.llm_draft and a.max_usd <= 0:
        ap.error("--llm-draft needs --max-usd > 0")
    res = build(a)
    print(json.dumps(res, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
